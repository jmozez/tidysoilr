test_that("texture triangle builds", {
  p <- soil_texture_triangle(png_profiles, sand, silt, clay, colour = wrb_group)
  expect_s3_class(p, "ggplot")
  expect_silent(ggplot2::ggplot_build(p))
  empty <- soil_texture_triangle(NULL, system = "fao", labels = FALSE)
  expect_s3_class(empty, "ggplot")
  expect_s3_class(soil_texture_triangle(png_profiles, sand, silt, clay), "ggplot")
})

test_that("autoplot methods build", {
  fits <- soil_vg_fit(soil_retention_lab, h_cm, theta, .by = sample)
  p1 <- autoplot(fits)
  expect_s3_class(p1, "ggplot")
  expect_silent(ggplot2::ggplot_build(p1))
  prof <- soil_profile(png_profiles, profile, top, bottom)
  p2 <- autoplot(prof, clay, max_profiles = 4)
  expect_s3_class(p2, "ggplot")
  expect_silent(ggplot2::ggplot_build(p2))
  expect_error(autoplot(prof, horizon), "numeric")
  spec <- soil_spectra(soil_nir, dplyr::starts_with("nm_"))
  p3 <- autoplot(spec, colour = clay)
  expect_s3_class(p3, "ggplot")
  expect_silent(ggplot2::ggplot_build(p3))
  expect_s3_class(autoplot(soil_snv(spec)), "ggplot")
})
